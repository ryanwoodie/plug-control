#!/usr/bin/env python3
"""Generate firmware/include/secrets.h and secrets/credentials.txt.

Owner passwords never go into the firmware: only the AES key derived from each
password (PBKDF2, same parameters as docs/app.js) and the topic id derived from
that key. Re-run this to change passwords, then reflash the board.

Usage:
  tools/make_secrets.py --owner pilot1 --owner pilot2 \
      --plug ACEBE6F17B6C:pilot1:"Plug A" --plug ACEBE6F17C50:pilot2:"Plug B"
  Optional: --password pilot1=SECRET (otherwise a random one is generated)
"""
import argparse, hashlib, os, secrets, string, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PBKDF2_ITERS = 100_000  # must match docs/app.js


def derive(user, password):
    key = hashlib.pbkdf2_hmac("sha256", password.encode(), f"plugctl1:{user.lower()}".encode(), PBKDF2_ITERS, 16)
    tid = hashlib.sha256(key + b"topic").hexdigest()[:20]
    return key, tid


def random_password():
    alphabet = "abcdefghjkmnpqrstuvwxyz23456789"
    return "-".join("".join(secrets.choice(alphabet) for _ in range(4)) for _ in range(4))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--owner", action="append", required=True)
    ap.add_argument("--plug", action="append", required=True, help="MAC:owner:name")
    ap.add_argument("--password", action="append", default=[], help="owner=password")
    a = ap.parse_args()

    given = dict(p.split("=", 1) for p in a.password)
    owners = []
    for user in a.owner:
        pw = given.get(user) or random_password()
        key, tid = derive(user, pw)
        owners.append((user.lower(), pw, key, tid))
    idx = {o[0]: i for i, o in enumerate(owners)}

    plugs = []
    for spec in a.plug:
        mac, owner, name = spec.split(":", 2)
        if owner.lower() not in idx:
            sys.exit(f"unknown owner {owner} for plug {mac}")
        plugs.append((mac.upper().replace(":", ""), idx[owner.lower()], name))

    ap_pass = "".join(secrets.choice(string.ascii_letters + string.digits) for _ in range(16))
    dev_id = secrets.token_hex(4)

    h = ["// Generated by tools/make_secrets.py. Do not commit.", "#pragma once", "#include <stdint.h>", "",
         f'#define AP_SSID "PlugCtl-{dev_id}"', f'#define AP_PASS "{ap_pass}"', "",
         "struct OwnerDef { const char *user; uint8_t key[16]; const char *tid; };",
         "struct PlugDef { const char *mac; uint8_t owner; const char *name; };", "",
         f"#define OWNER_COUNT {len(owners)}", "static const OwnerDef OWNERS[OWNER_COUNT] = {"]
    for user, _, key, tid in owners:
        h.append(f'  {{"{user}", {{{", ".join(f"0x{b:02x}" for b in key)}}}, "{tid}"}},')
    h += ["};", "", f"#define PLUG_COUNT {len(plugs)}", "static const PlugDef PLUGS[PLUG_COUNT] = {"]
    for mac, o, name in plugs:
        h.append(f'  {{"{mac}", {o}, "{name}"}},')
    h.append("};")

    with open(os.path.join(ROOT, "firmware/include/secrets.h"), "w") as f:
        f.write("\n".join(h) + "\n")

    os.makedirs(os.path.join(ROOT, "secrets"), exist_ok=True)
    lines = ["Plug controller credentials (keep private)", "",
             f"Board Wi-Fi (for the plugs / on-site page at http://192.168.4.1):",
             f"  SSID: PlugCtl-{dev_id}", f"  Password: {ap_pass}", "", "Web app logins:"]
    for user, pw, _, _ in owners:
        mine = ", ".join(n for m, o, n in plugs if owners[o][0] == user)
        lines.append(f"  {user} / {pw}   (plugs: {mine})")
    with open(os.path.join(ROOT, "secrets/credentials.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote firmware/include/secrets.h and secrets/credentials.txt")


if __name__ == "__main__":
    main()
